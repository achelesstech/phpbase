#!/usr/bin/env bash
# =============================================================================
# update-cloudflare-ips.sh — regenerate (or --check) the Cloudflare real-IP list
# =============================================================================
#   scripts/update-cloudflare-ips.sh           rewrite the committed include
#   scripts/update-cloudflare-ips.sh --check   exit 1 if the live list differs
#
# The list is COMMITTED, not fetched during `docker build`: builds stay
# hermetic and a change to who nginx trusts is a reviewable diff. CI runs
# --check weekly and warns; a human runs the rewrite and opens the PR.
# =============================================================================
set -euo pipefail
cd "$(dirname "$0")/.."

OUT="rootfs/etc/nginx/php-base/cloudflare-real-ip.conf"

live="$(
    { curl -fsS --max-time 20 https://www.cloudflare.com/ips-v4; echo
      curl -fsS --max-time 20 https://www.cloudflare.com/ips-v6; echo; } \
    | grep -E '^[0-9a-fA-F:.]+/[0-9]+$' | sort -u
)"
count="$(wc -l <<<"$live")"
[[ "$count" -ge 10 ]] || { echo "refusing: fetched only ${count} ranges" >&2; exit 1; }

committed="$(sed -n 's/^set_real_ip_from \(.*\);$/\1/p' "$OUT" | sort -u)"

if [[ "${1:-}" == "--check" ]]; then
    if [[ "$live" == "$committed" ]]; then
        echo "Cloudflare ranges unchanged (${count})"
        exit 0
    fi
    echo "::warning::Cloudflare ranges changed — run scripts/update-cloudflare-ips.sh and commit:"
    diff <(echo "$committed") <(echo "$live") || true
    exit 1
fi

{
    echo "# ============================================================================="
    echo "# cloudflare-real-ip.conf — Cloudflare edge ranges, trusted for X-Forwarded-For"
    echo "# ============================================================================="
    echo "# GENERATED by scripts/update-cloudflare-ips.sh — do not edit by hand."
    echo "# Source: https://www.cloudflare.com/ips-v4 and /ips-v6, fetched $(date -u +%Y-%m-%d)."
    echo "#"
    echo "# Included by the rendered real-IP config when NGINX_TRUST_CLOUDFLARE=1 (the"
    echo "# default). Behind Cloudflare -> Traefik -> nginx, Traefik appends the edge"
    echo "# address to X-Forwarded-For; without these ranges nginx stops at that hop and"
    echo "# every visitor appears to come from a Cloudflare IP."
    echo "# ============================================================================="
    sed 's/^/set_real_ip_from /; s/$/;/' <<<"$live"
} > "$OUT"
echo "wrote ${count} ranges to ${OUT}"
