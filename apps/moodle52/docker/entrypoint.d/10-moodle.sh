#!/bin/sh
# =============================================================================
# 10-moodle.sh — runs as www-data at container start
# =============================================================================
# Generates config.php from the environment if it does not already exist.
#
# This is a real script file, not a heredoc nested inside a Dockerfile heredoc.
# That matters: the previous revision nested `<<MOODLECFG` inside `<<'INIT'`
# inside `RUN cat <<...`, and the Redis block's `\\\$CFG` collapsed to a
# literal `\$CFG` in the generated PHP — a parse error that took the whole site
# down the moment Redis sessions were enabled. One level of quoting cannot
# produce that class of bug.
# =============================================================================
set -eu

APP_ROOT="${APP_ROOT:-/var/www/html}"
DATAROOT="${MOODLE_DATAROOT:-/var/moodledata}"
CONFIG="${APP_ROOT}/config.php"

# ── moodledata ───────────────────────────────────────────────────────────────
mkdir -p "${DATAROOT}/temp" "${DATAROOT}/cache" "${DATAROOT}/localcache" "${DATAROOT}/sessions" 2>/dev/null || true
chmod -R u+rwX,g+rwX "${DATAROOT}" 2>/dev/null || true

# ── CLI directory differs pre/post the 5.1 restructure ───────────────────────
if [ -d "${APP_ROOT}/public/admin/cli" ]; then
    CLI_DIR="${APP_ROOT}/public/admin/cli"
    SETUP_PATH="public/lib/setup.php"
else
    CLI_DIR="${APP_ROOT}/admin/cli"
    SETUP_PATH="lib/setup.php"
fi
export MOODLE_CLI_DIR="$CLI_DIR"

# ── config.php ───────────────────────────────────────────────────────────────
if [ -f "$CONFIG" ]; then
    echo "[moodle] config.php already present — leaving it alone"
elif [ -z "${MOODLE_DB_HOST:-}" ]; then
    echo "[moodle] WARNING: no config.php and MOODLE_DB_HOST is unset — not generating one"
else
    echo "[moodle] generating config.php"

    # sslproxy must be true behind a TLS-terminating proxy or Moodle
    # redirect-loops on its https wwwroot.
    if [ "${MOODLE_SSLPROXY:-true}" = "true" ]; then SSLPROXY=true; else SSLPROXY=false; fi

    # Unquoted heredoc: ${...} interpolates from the environment, \$ produces a
    # literal PHP variable sigil. Exactly one level of escaping.
    cat > "$CONFIG" <<PHPCONF
<?php
// Generated by the container entrypoint. Delete this file to regenerate.
unset(\$CFG);
global \$CFG;
\$CFG = new stdClass();

\$CFG->dbtype    = '${MOODLE_DB_TYPE:-mariadb}';
\$CFG->dblibrary = 'native';
\$CFG->dbhost    = '${MOODLE_DB_HOST}';
\$CFG->dbname    = '${MOODLE_DB_NAME:-moodle}';
\$CFG->dbuser    = '${MOODLE_DB_USER:-moodle}';
\$CFG->dbpass    = '${MOODLE_DB_PASSWORD:-}';
\$CFG->prefix    = '${MOODLE_DB_PREFIX:-mdl_}';
\$CFG->dboptions = [
    'dbpersist' => false,
    'dbsocket'  => false,
    'dbport'    => '${MOODLE_DB_PORT:-}',
];

\$CFG->wwwroot  = '${MOODLE_URL:-http://localhost:8080}';
\$CFG->dataroot = '${DATAROOT}';
\$CFG->admin    = 'admin';
\$CFG->directorypermissions = 02775;

// TLS terminates at the external reverse proxy.
\$CFG->sslproxy = ${SSLPROXY};

// Moodle 5.1+ Routing Engine — r.php is wired up in the nginx vhost.
\$CFG->routerconfigured = true;

// nginx serves moodledata files directly; see the /dataroot/ location.
\$CFG->xsendfile = 'X-Accel-Redirect';
\$CFG->xsendfilealiases = [
    '/dataroot/' => \$CFG->dataroot,
];

// Cron must never be reachable over the web.
\$CFG->cronclionly = true;

\$CFG->debug        = 0;
\$CFG->debugdisplay = 0;
\$CFG->pathtophp    = '/usr/local/bin/php';
\$CFG->pathtogs     = '/usr/bin/gs';
\$CFG->pathtodot    = '/usr/bin/dot';
PHPCONF

    # ── Redis sessions (required if you run more than one app replica) ───────
    if [ "${MOODLE_SESSION_HANDLER:-}" = "redis" ]; then
        echo "[moodle] enabling Redis session handler"
        cat >> "$CONFIG" <<PHPREDIS

\$CFG->session_handler_class = '\\core\\session\\redis';
\$CFG->session_redis_host    = '${MOODLE_SESSION_REDIS_HOST:-redis}';
\$CFG->session_redis_port    = ${MOODLE_SESSION_REDIS_PORT:-6379};
\$CFG->session_redis_database = ${MOODLE_SESSION_REDIS_DB:-0};
\$CFG->session_redis_prefix  = '${MOODLE_SESSION_REDIS_PREFIX:-mdl_sess_}';
\$CFG->session_redis_acquire_lock_timeout = 120;
\$CFG->session_redis_lock_expire = 7200;
PHPREDIS
    fi

    printf '\nrequire_once(__DIR__ . %s);\n' "'/${SETUP_PATH}'" >> "$CONFIG"

    # Fail loudly here rather than serving a white screen.
    php -l "$CONFIG" >/dev/null
    echo "[moodle] config.php generated and syntax-checked"
fi

# ── Sanity checks ────────────────────────────────────────────────────────────
[ -d "${APP_ROOT}/vendor" ] \
    || echo "[moodle] WARNING: vendor/ missing — Moodle 5.1+ requires 'composer install --no-dev --classmap-authoritative'"

# ── In-container cron ────────────────────────────────────────────────────────
# Moodle needs cron every minute or scheduled tasks silently stop. Use either
# this (MOODLE_RUN_CRON=true) or the cron sidecar in compose — never both.
if [ "${MOODLE_RUN_CRON:-false}" = "true" ]; then
    echo "[moodle] registering supervised cron runner"
    cat > /etc/supervisor/conf.d/moodle-cron.conf <<CRONCONF
[program:moodle-cron]
command                 = /usr/local/bin/moodle-cron.sh
directory               = ${APP_ROOT}
autostart               = true
autorestart             = true
startsecs               = 5
priority                = 20
stopsignal              = TERM
stdout_logfile          = /dev/fd/1
stdout_logfile_maxbytes = 0
stderr_logfile          = /dev/fd/2
stderr_logfile_maxbytes = 0
environment             = MOODLE_CLI_DIR="${CLI_DIR}"
CRONCONF
fi

# ── Upgrade on request ───────────────────────────────────────────────────────
if [ "${MOODLE_RUN_UPGRADE:-false}" = "true" ]; then
    echo "[moodle] running CLI upgrade"
    php "${CLI_DIR}/upgrade.php" --non-interactive
fi
